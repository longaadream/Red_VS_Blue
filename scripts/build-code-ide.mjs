import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const vendor = path.join(root, 'electron-editor/code-ide')
// The checked-in browser bundle works offline and needs no installed runtime dependencies.
await build({
  entryPoints: [path.join(vendor, 'index.mjs')],
  outfile: path.join(root, 'electron-editor/ui/code-ide.js'),
  bundle: true, format: 'iife', globalName: 'ContentCodeIDE', platform: 'browser', target: 'es2022',
  minify: true, legalComments: 'eof',
  banner: { js: '/* eslint-disable */\n// Generated by scripts/build-code-ide.mjs. Source: electron-editor/code-ide/.' },
})
const notices = []
const collect = directory => {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith('.')) continue
    const folder = path.join(directory, entry.name)
    if (entry.name.startsWith('@')) { collect(folder); continue }
    const license = fs.readdirSync(folder).find(file => /^licen[cs]e(?:\.md|\.txt)?$/i.test(file))
    if (license) notices.push(`## ${entry.name}\n\n${fs.readFileSync(path.join(folder, license), 'utf8')}`)
  }
}
collect(path.join(vendor, 'node_modules'))
fs.writeFileSync(path.join(root, 'electron-editor/ui/code-ide-LICENSES.txt'), notices.join('\n\n'))
