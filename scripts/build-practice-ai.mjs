import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
await build({
  entryPoints: [path.join(root, 'lib/practice/worker.ts')],
  outfile: path.join(root, 'data/pages/js/practice/engine.js'),
  bundle: true, platform: 'browser', format: 'iife', minify: true,
  supported: { 'template-literal': false },
  banner: { js: '/* eslint-disable -- generated by scripts/build-practice-ai.mjs */' },
  plugins: [{ name: 'practice-worker-runtime', setup(builder) {
    builder.onResolve({ filter: /^(?:node:)?fs$/ }, () => ({ path: path.join(root, 'lib/practice/vfs.ts') }))
    builder.onResolve({ filter: /^(?:node:)?path$/ }, () => ({ path: path.join(root, 'mobile-server/path-shim.ts') }))
    builder.onResolve({ filter: /(?:^@\/lib\/|[/\\])app-paths$/ }, () => ({ path: path.join(root, 'mobile-server/app-paths-shim.ts') }))
    builder.onResolve({ filter: /^(?:node:)?(?:crypto|zlib|os)$|^adm-zip$/ }, args => ({ path: args.path, namespace: 'practice-unused-node' }))
    builder.onLoad({ filter: /.*/, namespace: 'practice-unused-node' }, () => ({ contents: 'module.exports = { randomUUID: () => globalThis.crypto.randomUUID() }', loader: 'js' }))
  } }],
})
console.log('[practice] Built worker from current local sources')
