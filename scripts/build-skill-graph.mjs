import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { copyFileSync, mkdirSync } from 'node:fs'
// Share the same authoring contract with the Node editor without widening its
// TypeScript rootDir or changing the packaged main.js layout.
await build({
  entryPoints: [fileURLToPath(new URL('../lib/skill-graph/module-document.ts', import.meta.url))],
  outfile: fileURLToPath(new URL('../electron-editor/gameplay-module-core.cjs', import.meta.url)),
  bundle: true, format: 'cjs', platform: 'neutral', target: 'es2020',
  banner: { js: '// Generated by scripts/build-skill-graph.mjs; edit lib/skill-graph/module-*.ts.' },
})
mkdirSync(fileURLToPath(new URL('../electron-editor/dist/', import.meta.url)), { recursive: true })
copyFileSync(fileURLToPath(new URL('../electron-editor/gameplay-module-core.cjs', import.meta.url)), fileURLToPath(new URL('../electron-editor/dist/gameplay-module-core.cjs', import.meta.url)))
await build({
  entryPoints: [fileURLToPath(new URL('../electron-editor/content-graph-document.ts', import.meta.url))],
  outfile: fileURLToPath(new URL('../electron-editor/ui/content-graph-core.js', import.meta.url)),
  bundle: true, format: 'iife', globalName: 'ContentGraphCore', platform: 'browser', target: 'es2020',
  banner: { js: '// Generated by scripts/build-skill-graph.mjs; edit electron-editor/content-graph-document.ts and content-graph.ts.' },
  footer: { js: 'globalThis.ContentGraphCore = ContentGraphCore;' },
})
await build({
  entryPoints: [fileURLToPath(new URL('../electron-editor/skill-graph.ts', import.meta.url))],
  outfile: fileURLToPath(new URL('../electron-editor/ui/skill-graph-core.js', import.meta.url)),
  bundle: true, format: 'iife', globalName: 'SkillGraphCore', platform: 'browser', target: 'es2020',
  banner: { js: '// Generated by scripts/build-skill-graph.mjs; edit electron-editor/skill-graph.ts.' },
  footer: { js: 'globalThis.SkillGraphCore = SkillGraphCore;' },
})
// Keep the existing parser in a local Node bundle; authored code is parsed, never evaluated.
await build({
  entryPoints: [fileURLToPath(new URL('../electron-editor/source-flow.ts', import.meta.url))],
  outfile: fileURLToPath(new URL('../electron-editor/dist/source-flow.cjs', import.meta.url)),
  bundle: true, format: 'cjs', platform: 'node', target: 'node20', minify: true,
})
