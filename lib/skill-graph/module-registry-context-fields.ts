const ACTIVE_SURFACES: readonly GameplayModuleSurface[] = ['skill', 'card', 'rule', 'triggerSkill', 'pending']
const numberType: GameplayValueType = 'number'
const booleanType: GameplayValueType = 'boolean'
const stringType: GameplayValueType = 'string'
const playerType: GameplayValueType = 'player'
const cellType: GameplayValueType = 'cell'
const choiceType: GameplayValueType = 'choice'
const unknownType: GameplayValueType = 'unknown'
const nullableNumberType: GameplayValueType = { kind: 'nullable', value: numberType }
const nullableStringType: GameplayValueType = { kind: 'nullable', value: stringType }
const nullablePlayerType: GameplayValueType = { kind: 'nullable', value: playerType }
const nullablePieceType: GameplayValueType = { kind: 'nullable', value: 'piece' }
const cellListType: GameplayValueType = { kind: 'list', element: cellType }
const choiceListType: GameplayValueType = { kind: 'list', element: choiceType }

const CONTEXT_NUMBER_FIELDS = [
  'damage', 'actualDamage', 'heal', 'amount', 'targetX', 'targetY', 'turnNumber', 'fromX', 'fromY',
] as const
const CONTEXT_STRING_FIELDS = [
  'skillId', 'playerId', 'cardId', 'statusId', 'statusType',
] as const
const CONTEXT_BOOLEAN_FIELDS = ['cancelled'] as const

const CONTEXT_FIELD_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  ...Object.fromEntries(CONTEXT_NUMBER_FIELDS.map(field => [field, nullableNumberType])),
  ...Object.fromEntries(CONTEXT_STRING_FIELDS.map(field => [field, nullableStringType])),
  ...Object.fromEntries(CONTEXT_BOOLEAN_FIELDS.map(field => [field, booleanType])),
})

/**
 * Version 2 adds the non-scalar host selections that older event helpers
 * exposed directly.  Version 1 stays byte-for-byte compatible for all of its
 * published scalar selections; migrations use this version only for the new
 * closed fields below.
 */
const CONTEXT_V2_FIELD_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  ...CONTEXT_FIELD_TYPES,
  isSinglePieceTargetAction: booleanType,
  reservedCells: cellListType,
  selectedTargets: choiceListType,
  selectedOption: nullableStringType,
})
const CONTEXT_V2_LIST_FIELDS = new Set(['reservedCells', 'selectedTargets'])
const CONTEXT_V2_STRICT_BOOLEAN_FIELDS = new Set(['isSinglePieceTargetAction'])
const CONTEXT_V2_STRING_FIELDS = new Set(['selectedOption'])

/** Current dynamic-card values need the execution-context fallbacks owned by
 * the card runtime. They are additive so published context.field@1/@2 bytes
 * remain unchanged. */
const CONTEXT_CARD_FIELD_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  currentCardId: stringType,
  currentCardType: stringType,
})

/** Rule source fallbacks need player references, while the original scalar
 * context reader intentionally exposes playerId as nullable text.  Keep this
 * table additive so the published context.field@1/@2 descriptors retain
 * their existing metadata and generated bytes. */
const CONTEXT_RULE_FIELD_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  ruleOwnerPlayerId: nullablePlayerType,
  playerId: nullablePlayerType,
  ruleRewrittenPrimaryTargetPieceId: nullablePieceType,
})

/** Direct event facts need an additive version because v1 normalizes a missing
 * event property to null.  The retired readers returned undefined for a
 * missing property and otherwise preserved the host value exactly. */
const EVENT_FIELD_V2_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  type: nullableStringType,
  playerId: nullablePlayerType,
  actualDamage: nullableNumberType,
  movementKind: nullableStringType,
})

/** battle.field@1 uses the invalid sentinel for a missing turn property and
 * preview battle.field@2 has a different raw-field contract; these aliases
 * require their own active-surface version with the old undefined result. */
const BATTLE_FIELD_V2_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  turnNumber: numberType,
  currentPlayerId: playerType,
})

const SKILL_NUMBER_FIELDS = ['powerMultiplier', 'actionPointCost', 'chargeCost', 'cooldown'] as const
const SKILL_STRING_FIELDS = ['name', 'description'] as const
const SKILL_FIELD_TYPES: Readonly<Record<string, GameplayValueType>> = Object.freeze({
  ...Object.fromEntries(SKILL_NUMBER_FIELDS.map(field => [field, numberType])),
  ...Object.fromEntries(SKILL_STRING_FIELDS.map(field => [field, stringType])),
})

const port = (
  name: string,
  type: GameplayValueType,
  options: Omit<GameplayPort, 'name' | 'type'> = {},
): GameplayPort => ({ name, type, ...options })

const parameter = (
  name: string,
  type: GameplayValueType,
  options: Omit<GameplayParameter, 'name' | 'type'> = {},
): GameplayParameter => ({ name, type, ...options })

const pure = (reads: readonly string[]): GameplayEffectMetadata => ({ pure: true, previewSafe: false, reads })

const define = (
  value: Omit<Descriptor, 'version' | 'allowedSurfaces'> & { allowedSurfaces?: readonly GameplayModuleSurface[] },
): Descriptor => ({
  version: '1',
  allowedSurfaces: value.allowedSurfaces ?? ACTIVE_SURFACES,
  ...value,
})

const host = (ctx: Context): string => ctx.surface === 'pending' ? 'ctx' : 'context'

function selectedField(ctx: Context, fields: Readonly<Record<string, GameplayValueType>>): string {
  const value = ctx.parameters.field
  if (typeof value !== 'string' || !Object.prototype.hasOwnProperty.call(fields, value)) {
    throw new Error(`module ${ctx.moduleId}: unsupported field`)
  }
  return value
}

function contextFieldLowering(ctx: Context): string {
  const selected = selectedField(ctx, CONTEXT_FIELD_TYPES)
  const source = host(ctx)
  const key = ctx.emitLiteral(selected)
  const numeric = CONTEXT_NUMBER_FIELDS.includes(selected as typeof CONTEXT_NUMBER_FIELDS[number])
  const text = CONTEXT_STRING_FIELDS.includes(selected as typeof CONTEXT_STRING_FIELDS[number])
  const conversion = numeric
    ? 'raw==null?null:Number(raw)'
    : text
      ? 'raw==null?null:String(raw)'
      : 'Boolean(raw)'
  return `(function(record,key){var defined=record!=null&&Object.prototype.hasOwnProperty.call(record,key)&&record[key]!==undefined;var raw=defined?record[key]:undefined;return {value:${conversion},defined:defined};})(${source},${key})`
}

function contextFieldV2Lowering(ctx: Context): string {
  const selected = selectedField(ctx, CONTEXT_V2_FIELD_TYPES)
  const source = host(ctx)
  const key = ctx.emitLiteral(selected)
  const numeric = CONTEXT_NUMBER_FIELDS.includes(selected as typeof CONTEXT_NUMBER_FIELDS[number])
  const text = CONTEXT_STRING_FIELDS.includes(selected as typeof CONTEXT_STRING_FIELDS[number])
  const conversion = CONTEXT_V2_LIST_FIELDS.has(selected)
    ? 'Array.isArray(raw)?raw:[]'
    : CONTEXT_V2_STRICT_BOOLEAN_FIELDS.has(selected)
      ? 'raw===true'
      : CONTEXT_V2_STRING_FIELDS.has(selected)
        ? 'raw==null?null:String(raw)'
        : numeric
          ? 'raw==null?null:Number(raw)'
          : text
            ? 'raw==null?null:String(raw)'
            : 'Boolean(raw)'
  return `(function(record,key){var defined=record!=null&&Object.prototype.hasOwnProperty.call(record,key)&&record[key]!==undefined;var raw=defined?record[key]:undefined;return {value:${conversion},defined:defined};})(${source},${key})`
}

function contextCardFieldLowering(ctx: Context): string {
  const selected = selectedField(ctx, CONTEXT_CARD_FIELD_TYPES)
  const source = host(ctx)
  if (selected === 'currentCardType') {
    return `(function(record){return record!=null&&typeof record.type==="string"?record.type:"";})(${source})`
  }
  return `(function(record){if(record==null||typeof record!=="object")return "";var card=record.card,id=card!=null&&typeof card==="object"?card.id:undefined;if(id==null){var instance=record.cardInstance;id=instance!=null&&typeof instance==="object"?instance.cardId:undefined;}return typeof id==="string"?id:"";})(${source})`
}

function contextRuleFieldLowering(ctx: Context): string {
  const selected = selectedField(ctx, CONTEXT_RULE_FIELD_TYPES)
  const source = host(ctx)
  const key = ctx.emitLiteral(selected)
  return `(function(record,key){var defined=record!=null&&Object.prototype.hasOwnProperty.call(record,key)&&record[key]!==undefined;var raw=defined?record[key]:undefined;return {value:raw==null?null:String(raw),defined:defined};})(${source},${key})`
}

function skillFieldLowering(ctx: Context): string {
  const selected = selectedField(ctx, SKILL_FIELD_TYPES)
  return `${host(ctx)}.skill[${ctx.emitLiteral(selected)}]`
}

function runtime(ctx: Context): string {
  return ctx.surface === 'pending' ? 'ctx.flow' : 'flow'
}

function eventFieldV2Lowering(ctx: Context): string {
  const selected = selectedField(ctx, EVENT_FIELD_V2_TYPES)
  return `{value:(${runtime(ctx)}.event.read())[${ctx.emitLiteral(selected)}]}`
}

function battle(ctx: Context): string {
  return ctx.surface === 'pending' ? 'ctx.battle' : 'battle'
}

function battleFieldV2Lowering(ctx: Context): string {
  const selected = selectedField(ctx, BATTLE_FIELD_V2_TYPES)
  return `{value:(${battle(ctx)}.turn)[${ctx.emitLiteral(selected)}]}`
}

