/**
 * Author-owned, data-only code blocks.
 *
 * A code block is a small pending-surface graph whose only root host value is
 * a typed `payload` record.  The record carries invocation arguments (for
 * example an explicit target piece); the block definition never captures a
 * live host object.  Compilation is delegated to the existing gameplay-module
 * compiler and its trusted registry.  This module deliberately does not add an
 * interpreter or an author-provided lowerer.
 */

import { compileGameplayModuleGraph } from './module-compiler'
import { GAMEPLAY_MODULE_REGISTRY } from './module-registry'
import {
  GAMEPLAY_MODULE_GRAPH_VERSION,
  type GameplayModuleCompilerOptions,
  type GameplayModuleCompileResult,
  type GameplayModuleGraph,
  type GameplayModuleRegistry,
  type GameplayPort,
  type GameplayRecordSchema,
  type GameplayValueType,
} from './module-types'

export const AUTHOR_CODE_BLOCK_VERSION = 'rvb-author-code-block/v1' as const

/** The default schema name used by `createAuthorCodeBlock` callers. */
export const AUTHOR_CODE_BLOCK_ARGUMENT_SCHEMA_ID = 'author-code-block.arguments' as const
export const AUTHOR_CODE_BLOCK_ARGUMENT_SCHEMA_VERSION = '1' as const

const AUTHOR_CODE_BLOCK_ARGUMENT_SCHEMA_REF = `${AUTHOR_CODE_BLOCK_ARGUMENT_SCHEMA_ID}@${AUTHOR_CODE_BLOCK_ARGUMENT_SCHEMA_VERSION}`

const VALUE_TYPE_NAMES = new Set([
  'number', 'boolean', 'string', 'piece', 'player', 'cell', 'path', 'card',
  'content', 'status', 'event', 'choice', 'record', 'null', 'never', 'unknown', 'any',
])

type DataRecord = Record<string, unknown>

export type AuthorCodeBlockSignature = {
  readonly inputs: readonly GameplayPort[]
  readonly outputs?: readonly GameplayPort[]
}

/**
 * The persisted author shape.  `graph` is the only executable definition;
 * generated compiler output is intentionally absent from this type.
 */
export type AuthorCodeBlock = {
  readonly version: typeof AUTHOR_CODE_BLOCK_VERSION
  readonly id: string
  readonly graph: GameplayModuleGraph
  readonly signature?: AuthorCodeBlockSignature
}

export type AuthorCodeBlockCreateInput = {
  readonly id: string
  readonly graph: GameplayModuleGraph
  readonly signature?: AuthorCodeBlockSignature
}

/** Runtime values are intentionally not part of the persisted block type. */
export type AuthorCodeBlockArguments = Readonly<Record<string, unknown>>

export type AuthorCodeBlockArgumentBinding = {
  /** Pass this record as `ctx.payload` when invoking the compiled pending function. */
  readonly payload: Readonly<Record<string, unknown>>
}

export type AuthorCodeBlockCompilation = {
  readonly definition: AuthorCodeBlock
  readonly signature: AuthorCodeBlockSignature
  /** Generated by the trusted gameplay compiler; never supplied by authors. */
  readonly compiled: GameplayModuleCompileResult
}

export type AuthorCodeBlockInvocation = AuthorCodeBlockCompilation & {
  readonly argumentBinding: AuthorCodeBlockArgumentBinding
}

export class AuthorCodeBlockValidationError extends Error {
  readonly code: string
  readonly path?: string

  constructor(message: string, path?: string, code = 'AUTHOR_CODE_BLOCK_INVALID') {
    super(path ? `${message} (${path})` : message)
    this.name = 'AuthorCodeBlockValidationError'
    this.code = code
    this.path = path
  }
}

function fail(message: string, path: string, code = 'AUTHOR_CODE_BLOCK_INVALID'): never {
  throw new AuthorCodeBlockValidationError(message, path, code)
}

function own(record: DataRecord, key: string): boolean {
  return Object.prototype.hasOwnProperty.call(record, key)
}

function isPlainObject(value: unknown): value is DataRecord {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return false
  const prototype = Object.getPrototypeOf(value)
  if (prototype === Object.prototype || prototype === null) return true
  // Accept an object crossing a VM/iframe boundary while rejecting class
  // instances and objects with a custom prototype chain.
  if (typeof prototype !== 'object' || prototype === null || Object.getPrototypeOf(prototype) !== null) return false
  const constructor = Object.getOwnPropertyDescriptor(prototype, 'constructor')
  return Boolean(
    constructor
      && 'value' in constructor
      && typeof constructor.value === 'function'
      && constructor.value.name === 'Object',
  )
}

function isPlainArray(value: unknown): value is readonly unknown[] {
  if (!Array.isArray(value)) return false
  const prototype = Object.getPrototypeOf(value)
  if (prototype === Array.prototype || prototype === null) return true
  if (typeof prototype !== 'object' || prototype === null || Object.getPrototypeOf(prototype) !== null) return false
  const constructor = Object.getOwnPropertyDescriptor(prototype, 'constructor')
  return Boolean(
    constructor
      && 'value' in constructor
      && typeof constructor.value === 'function'
      && constructor.value.name === 'Array',
  )
}

function safeName(value: unknown, path: string): string {
  if (typeof value !== 'string' || value.trim().length === 0) fail('must be a non-empty string', path, 'AUTHOR_CODE_BLOCK_INVALID_NAME')
  if (value === '__proto__' || value === 'prototype' || value === 'constructor') fail(`unsafe name "${value}"`, path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
  return value
}

function nonEmptyText(value: unknown, path: string): string {
  if (typeof value !== 'string' || value.trim().length === 0) fail('must be non-empty text', path)
  return value
}

function assertAllowed(record: DataRecord, keys: readonly string[], path: string): void {
  const allowed = new Set(keys)
  for (const key of Object.keys(record)) if (!allowed.has(key)) fail(`unknown field "${key}"`, `${path}.${key}`, 'AUTHOR_CODE_BLOCK_UNKNOWN_FIELD')
}

/**
 * Clone the persisted definition while checking the full data-only boundary.
 * Reading property values is safe only after descriptors have been confirmed
 * to be ordinary data properties.  The active set detects cycles without
 * rejecting two independent equal subtrees.
 */
function cloneDataOnly(value: unknown, path = 'block', active = new WeakSet<object>()): unknown {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return value
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) fail('numbers must be finite', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
    return value
  }
  if (typeof value === 'undefined') fail('undefined is not serializable', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
  if (typeof value === 'function') fail('functions are not allowed in a code block', path, 'AUTHOR_CODE_BLOCK_FUNCTION')
  if (typeof value === 'symbol' || typeof value === 'bigint') fail('non-JSON values are not allowed in a code block', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
  if (typeof value !== 'object') fail('unsupported value in a code block', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
  if (active.has(value)) fail('cycles are not allowed in a code block', path, 'AUTHOR_CODE_BLOCK_CYCLE')
  active.add(value)

  try {
    if (Array.isArray(value)) {
      if (!isPlainArray(value)) fail('arrays must use the ordinary array prototype', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
      const lengthDescriptor = Object.getOwnPropertyDescriptor(value, 'length')
      if (!lengthDescriptor || !('value' in lengthDescriptor) || lengthDescriptor.value !== value.length) {
        fail('array length must be a data property', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
      }
      for (const key of Reflect.ownKeys(value)) {
        if (typeof key !== 'string') fail('symbol keys are not allowed', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
        if (key === 'length') continue
        if (!/^(0|[1-9][0-9]*)$/.test(key) || Number(key) >= value.length) fail('array properties are not allowed', `${path}[${key}]`, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
        const descriptor = Object.getOwnPropertyDescriptor(value, key)
        if (!descriptor || !('value' in descriptor) || !descriptor.enumerable) fail('array entries must be enumerable data properties', `${path}[${key}]`, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
      }
      const result: unknown[] = []
      for (let index = 0; index < value.length; index += 1) {
        if (!Object.prototype.hasOwnProperty.call(value, index)) fail('sparse arrays are not allowed', `${path}[${index}]`, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
        result.push(cloneDataOnly(value[index], `${path}[${index}]`, active))
      }
      return result
    }

    if (!isPlainObject(value)) fail('code block values must be plain objects', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
    const result: DataRecord = Object.create(null) as DataRecord
    for (const key of Reflect.ownKeys(value)) {
      if (typeof key !== 'string') fail('symbol keys are not allowed', path, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
      if (key === '__proto__' || key === 'prototype' || key === 'constructor') fail(`unsafe object key "${key}"`, `${path}.${key}`, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
      const descriptor = Object.getOwnPropertyDescriptor(value, key)
      if (!descriptor || !('value' in descriptor) || !descriptor.enumerable) fail('accessor and non-enumerable properties are not allowed', `${path}.${key}`, 'AUTHOR_CODE_BLOCK_UNSAFE_VALUE')
      result[key] = cloneDataOnly(descriptor.value, `${path}.${key}`, active)
    }
    return result
  } finally {
    active.delete(value)
  }
}

function asRecord(value: unknown, path: string): DataRecord {
  if (!isPlainObject(value)) fail('expected a plain object', path, 'AUTHOR_CODE_BLOCK_SHAPE')
  return value
}

function isGameplayTypeName(value: string): boolean {
  return VALUE_TYPE_NAMES.has(value)
}

function normalizeType(value: unknown, path: string): GameplayValueType {
  if (typeof value === 'string') {
    if (!isGameplayTypeName(value)) fail(`unsupported value type "${value}"`, path, 'AUTHOR_CODE_BLOCK_TYPE')
    if (value === 'any' || value === 'unknown' || value === 'never') fail('universal or bottom types are not valid author arguments', path, 'AUTHOR_CODE_BLOCK_TYPE')
    return value as GameplayValueType
  }
  const record = asRecord(value, path)
  const kind = record.kind
  if (kind === 'list') {
    assertAllowed(record, ['kind', 'element'], path)
    if (!own(record, 'element')) fail('list type requires an element', path, 'AUTHOR_CODE_BLOCK_TYPE')
    return { kind: 'list', element: normalizeType(record.element, `${path}.element`) }
  }
  if (kind === 'set') {
    assertAllowed(record, ['kind', 'element'], path)
    if (!own(record, 'element')) fail('set type requires an element', path, 'AUTHOR_CODE_BLOCK_TYPE')
    return { kind: 'set', element: normalizeType(record.element, `${path}.element`) }
  }
  if (kind === 'map') {
    assertAllowed(record, ['kind', 'key', 'value'], path)
    if (!own(record, 'key')) fail('map type requires a key type', path, 'AUTHOR_CODE_BLOCK_TYPE')
    if (!own(record, 'value')) fail('map type requires a value type', path, 'AUTHOR_CODE_BLOCK_TYPE')
    return {
      kind: 'map',
      key: normalizeType(record.key, `${path}.key`),
      value: normalizeType(record.value, `${path}.value`),
    }
  }
  if (kind === 'nullable') {
    assertAllowed(record, ['kind', 'value'], path)
    if (!own(record, 'value')) fail('nullable type requires a value', path, 'AUTHOR_CODE_BLOCK_TYPE')
    return { kind: 'nullable', value: normalizeType(record.value, `${path}.value`) }
  }
  if (kind === 'record') {
    assertAllowed(record, ['kind', 'schema'], path)
    return { kind: 'record', schema: nonEmptyText(record.schema, `${path}.schema`) }
  }
  fail('unsupported value type descriptor', path, 'AUTHOR_CODE_BLOCK_TYPE')
}

function normalizePort(value: unknown, path: string): GameplayPort {
  const record = asRecord(value, path)
  assertAllowed(record, ['name', 'type', 'optional', 'nullable', 'label', 'description'], path)
  const result: DataRecord = {
    name: safeName(record.name, `${path}.name`),
    type: normalizeType(record.type, `${path}.type`),
  }
  for (const key of ['optional', 'nullable'] as const) {
    if (record[key] !== undefined) {
      if (typeof record[key] !== 'boolean') fail(`${key} must be a boolean`, `${path}.${key}`, 'AUTHOR_CODE_BLOCK_TYPE')
      result[key] = record[key]
    }
  }
  for (const key of ['label', 'description'] as const) if (record[key] !== undefined) result[key] = nonEmptyText(record[key], `${path}.${key}`)
  return result as GameplayPort
}

function normalizePorts(value: unknown, path: string): readonly GameplayPort[] {
  if (!Array.isArray(value)) fail('ports must be an array', path, 'AUTHOR_CODE_BLOCK_SHAPE')
  const result = value.map((entry, index) => normalizePort(entry, `${path}[${index}]`))
  const names = new Set<string>()
  for (const port of result) {
    if (names.has(port.name)) fail(`duplicate port "${port.name}"`, path, 'AUTHOR_CODE_BLOCK_DUPLICATE_PORT')
    names.add(port.name)
  }
  return result
}

function sameData(left: unknown, right: unknown): boolean {
  if (left === right) return true
  if (typeof left !== typeof right || left === null || right === null) return false
  if (Array.isArray(left) || Array.isArray(right)) {
    if (!Array.isArray(left) || !Array.isArray(right) || left.length !== right.length) return false
    return left.every((entry, index) => sameData(entry, right[index]))
  }
  if (typeof left === 'object' && typeof right === 'object') {
    const a = left as DataRecord
    const b = right as DataRecord
    const aKeys = Object.keys(a)
    const bKeys = Object.keys(b)
    if (aKeys.length !== bKeys.length || aKeys.some(key => !own(b, key))) return false
    return aKeys.every(key => sameData(a[key], b[key]))
  }
  return false
}

function moduleSchemaKey(id: string, version: string): string {
  return `${id}@${version}`
}

function findArgumentSchema(graph: DataRecord, path: string): GameplayRecordSchema {
  // `payload` is the only persisted block input.  Trusted registry lowerers
  // may still read the host's current flow/context while this graph executes;
  // that context is supplied ephemerally by the host and is never captured in
  // the serializable block definition.
  const hostBindings = asRecord(graph.hostBindings, `${path}.hostBindings`)
  const hostNames = Object.keys(hostBindings)
  if (hostNames.length !== 1 || hostNames[0] !== 'payload') {
    fail('author code blocks must receive explicit arguments through the pending payload', `${path}.hostBindings`, 'AUTHOR_CODE_BLOCK_HOST_BINDING')
  }
  const payload = asRecord(hostBindings.payload, `${path}.hostBindings.payload`)
  if (payload.kind !== 'record' || typeof payload.schema !== 'string' || payload.schema.trim().length === 0) {
    fail('pending payload must use a typed record schema', `${path}.hostBindings.payload`, 'AUTHOR_CODE_BLOCK_HOST_BINDING')
  }

  const schemas = graph.schemas
  if (!Array.isArray(schemas)) fail('author code block graph must declare its payload schema', `${path}.schemas`, 'AUTHOR_CODE_BLOCK_SCHEMA')
  const matches = schemas.filter(value => {
    const schema = asRecord(value, `${path}.schemas`)
    return schema.id === payload.schema || moduleSchemaKey(String(schema.id), String(schema.version)) === payload.schema
  })
  if (matches.length === 0) fail(`payload schema "${payload.schema}" is not declared by the graph`, `${path}.hostBindings.payload.schema`, 'AUTHOR_CODE_BLOCK_SCHEMA')
  if (matches.length > 1 && !payload.schema.includes('@')) fail('payload schema reference is ambiguous; use id@version', `${path}.hostBindings.payload.schema`, 'AUTHOR_CODE_BLOCK_SCHEMA')
  return matches[0] as GameplayRecordSchema
}

function graphPorts(graph: DataRecord, key: 'outputs'): readonly GameplayPort[] {
  return graph[key] === undefined ? [] : normalizePorts(graph[key], `graph.${key}`)
}

type PreparedAuthorCodeBlock = {
  readonly definition: AuthorCodeBlock
  readonly signature: AuthorCodeBlockSignature
  readonly argumentFields: readonly GameplayPort[]
  readonly compiled: GameplayModuleCompileResult
}

function prepareAuthorCodeBlock(
  value: unknown,
  registry: GameplayModuleRegistry,
  compilerOptions?: GameplayModuleCompilerOptions,
): PreparedAuthorCodeBlock {
  const cloned = cloneDataOnly(value)
  const record = asRecord(cloned, 'block')
  assertAllowed(record, ['version', 'id', 'graph', 'signature'], 'block')
  if (record.version !== AUTHOR_CODE_BLOCK_VERSION) fail(`unsupported author code block version "${String(record.version)}"`, 'block.version', 'AUTHOR_CODE_BLOCK_VERSION')
  const id = safeName(record.id, 'block.id')
  const graphRecord = asRecord(record.graph, 'block.graph')
  if (graphRecord.version !== GAMEPLAY_MODULE_GRAPH_VERSION) fail('author code block graph has an incompatible version', 'block.graph.version', 'AUTHOR_CODE_BLOCK_GRAPH_VERSION')
  if (graphRecord.surface !== 'pending') fail('author code blocks must use the pending surface', 'block.graph.surface', 'AUTHOR_CODE_BLOCK_SURFACE')
  if (graphRecord.inputBindings !== undefined) {
    const bindings = asRecord(graphRecord.inputBindings, 'block.graph.inputBindings')
    if (Object.keys(bindings).length > 0) fail('author code block arguments cannot be static graph bindings', 'block.graph.inputBindings', 'AUTHOR_CODE_BLOCK_HOST_BINDING')
  }
  if (graphRecord.inputs !== undefined) {
    const inputs = normalizePorts(graphRecord.inputs, 'block.graph.inputs')
    if (inputs.length !== 1 || inputs[0].name !== 'payload') fail('author code blocks may expose only the pending payload root input', 'block.graph.inputs', 'AUTHOR_CODE_BLOCK_HOST_BINDING')
  }

  const argumentSchema = findArgumentSchema(graphRecord, 'block.graph')
  const argumentFields = normalizePorts(argumentSchema.fields, 'block.graph.schemas.payload.fields')
  const outputs = graphPorts(graphRecord, 'outputs')
  let signature: AuthorCodeBlockSignature
  if (record.signature === undefined) {
    signature = { inputs: argumentFields, ...(outputs.length > 0 ? { outputs } : {}) }
  } else {
    const signatureRecord = asRecord(record.signature, 'block.signature')
    assertAllowed(signatureRecord, ['inputs', 'outputs'], 'block.signature')
    const inputs = normalizePorts(signatureRecord.inputs, 'block.signature.inputs')
    if (!sameData(inputs, argumentFields)) fail('signature inputs must match the payload record fields', 'block.signature.inputs', 'AUTHOR_CODE_BLOCK_SIGNATURE_MISMATCH')
    let normalizedOutputs: readonly GameplayPort[] | undefined
    if (signatureRecord.outputs !== undefined) {
      normalizedOutputs = normalizePorts(signatureRecord.outputs, 'block.signature.outputs')
      if (!sameData(normalizedOutputs, outputs)) fail('signature outputs must match the graph outputs', 'block.signature.outputs', 'AUTHOR_CODE_BLOCK_SIGNATURE_MISMATCH')
    }
    signature = { inputs, ...(normalizedOutputs === undefined ? {} : { outputs: normalizedOutputs }) }
  }

  // Compile the fresh clone as part of validation. This checks every call,
  // type port, composite, continuation, and existing compiler budget.
  const compiled = compileGameplayModuleGraph(graphRecord as unknown as GameplayModuleGraph, registry, compilerOptions)
  const definition: AuthorCodeBlock = {
    version: AUTHOR_CODE_BLOCK_VERSION,
    id,
    graph: graphRecord as unknown as GameplayModuleGraph,
    ...(record.signature === undefined ? {} : { signature }),
  }
  return { definition, signature, argumentFields, compiled }
}

function checkOpaqueArgumentValue(value: unknown, path: string): void {
  if (value === undefined || typeof value === 'function' || typeof value === 'symbol' || typeof value === 'bigint') {
    fail('argument values cannot contain functions or non-serializable primitives', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
  }
  if (value && typeof value === 'object') {
    for (const key of Reflect.ownKeys(value)) {
      const descriptor = Object.getOwnPropertyDescriptor(value, key)
      if (!descriptor || !('value' in descriptor)) fail('argument objects cannot contain accessors', `${path}.${String(key)}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      if (typeof key === 'symbol' || typeof descriptor.value === 'function' || typeof descriptor.value === 'symbol' || typeof descriptor.value === 'bigint') {
        fail('argument values cannot contain callbacks or symbols', `${path}.${String(key)}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      }
    }
  }
}

function effectiveArgumentType(port: GameplayPort): GameplayValueType {
  return port.nullable ? { kind: 'nullable', value: port.type } : port.type
}

function validateArgumentValue(value: unknown, type: GameplayValueType, schemas: ReadonlyMap<string, GameplayRecordSchema>, path: string): void {
  if (typeof type === 'object' && type.kind === 'nullable') {
    if (value === null) return
    validateArgumentValue(value, type.value, schemas, path)
    return
  }
  if (typeof type === 'object' && type.kind === 'list') {
    if (!Array.isArray(value)) fail('argument expects an array', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    for (let index = 0; index < value.length; index += 1) {
      if (!Object.prototype.hasOwnProperty.call(value, index)) fail('argument arrays cannot be sparse', `${path}[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      validateArgumentValue(value[index], type.element, schemas, `${path}[${index}]`)
    }
    return
  }
  if (typeof type === 'object' && type.kind === 'set') {
    if (!isPlainObject(value)) fail('set arguments must use a serialized object', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    checkOpaqueArgumentValue(value, path)
    assertAllowed(value, ['format', 'items'], path)
    if (value.format !== 'author-set/v1') fail('set arguments must use author-set/v1', `${path}.format`, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    if (!Array.isArray(value.items)) fail('set arguments require an items array', `${path}.items`, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    for (let index = 0; index < value.items.length; index += 1) {
      if (!Object.prototype.hasOwnProperty.call(value.items, index)) fail('set argument arrays cannot be sparse', `${path}.items[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      validateArgumentValue(value.items[index], type.element, schemas, `${path}.items[${index}]`)
    }
    return
  }
  if (typeof type === 'object' && type.kind === 'map') {
    if (!isPlainObject(value)) fail('map arguments must use a serialized object', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    checkOpaqueArgumentValue(value, path)
    assertAllowed(value, ['format', 'entries'], path)
    if (value.format !== 'author-map/v1') fail('map arguments must use author-map/v1', `${path}.format`, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    if (!Array.isArray(value.entries)) fail('map arguments require an entries array', `${path}.entries`, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    for (let index = 0; index < value.entries.length; index += 1) {
      if (!Object.prototype.hasOwnProperty.call(value.entries, index)) fail('map argument arrays cannot be sparse', `${path}.entries[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      const entry = value.entries[index]
      if (!Array.isArray(entry) || entry.length !== 2) fail('map entries must be two-item tuples', `${path}.entries[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
      checkOpaqueArgumentValue(entry, `${path}.entries[${index}]`)
      for (const key of Reflect.ownKeys(entry)) {
        if (typeof key !== 'string' || (key !== '0' && key !== '1' && key !== 'length')) fail('map entries must be dense tuples', `${path}.entries[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      }
      const lengthDescriptor = Object.getOwnPropertyDescriptor(entry, 'length')
      if (!lengthDescriptor || !('value' in lengthDescriptor) || lengthDescriptor.value !== 2 || !Object.prototype.hasOwnProperty.call(entry, 0) || !Object.prototype.hasOwnProperty.call(entry, 1)) fail('map entries must be dense tuples', `${path}.entries[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      validateArgumentValue(entry[0], type.key, schemas, `${path}.entries[${index}][0]`)
      validateArgumentValue(entry[1], type.value, schemas, `${path}.entries[${index}][1]`)
    }
    return
  }
  if (typeof type === 'object' && type.kind === 'record') {
    if (!isPlainObject(value)) fail('argument expects a typed record object', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    const schema = [...schemas.values()].find(entry => entry.id === type.schema || moduleSchemaKey(entry.id, entry.version) === type.schema)
    if (!schema) fail(`unknown argument record schema "${type.schema}"`, path, 'AUTHOR_CODE_BLOCK_ARGUMENT_SCHEMA')
    const fields = new Map(schema.fields.map(field => [field.name, field]))
    for (const key of Object.keys(value)) if (!fields.has(key)) fail(`unknown argument field "${key}"`, `${path}.${key}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    for (const field of schema.fields) if (own(value, field.name)) validateArgumentValue(value[field.name], effectiveArgumentType(field), schemas, `${path}.${field.name}`)
    return
  }
  if (type === 'number') {
    if (typeof value !== 'number' || !Number.isFinite(value)) fail('argument expects a finite number', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    return
  }
  if (type === 'boolean') {
    if (typeof value !== 'boolean') fail('argument expects a boolean', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    return
  }
  if (type === 'string') {
    if (typeof value !== 'string') fail('argument expects text', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    return
  }
  if (type === 'null') {
    if (value !== null) fail('argument expects null', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    return
  }
  if (type === 'cell') {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) fail('argument expects a cell object', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    checkOpaqueArgumentValue(value, path)
    const cell = value as DataRecord
    if (typeof cell.x !== 'number' || !Number.isInteger(cell.x) || typeof cell.y !== 'number' || !Number.isInteger(cell.y)) fail('cell arguments require integer x and y fields', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    return
  }
  if (type === 'path') {
    if (!Array.isArray(value)) fail('argument expects a path array', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    checkOpaqueArgumentValue(value, path)
    for (let index = 0; index < value.length; index += 1) {
      if (!Object.prototype.hasOwnProperty.call(value, index)) fail('path argument arrays cannot be sparse', `${path}[${index}]`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
      validateArgumentValue(value[index], 'cell', schemas, `${path}[${index}]`)
    }
    return
  }
  if (type === 'record') {
    if (!isPlainObject(value)) fail('argument expects a record object', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
    checkOpaqueArgumentValue(value, path)
    return
  }
  // Entity references are opaque runtime values. They are deliberately kept
  // out of the block definition and are only checked for executable own data.
  if (value === null || (typeof value !== 'string' && typeof value !== 'object')) {
    fail('argument entity references must be an opaque ID or object', path, 'AUTHOR_CODE_BLOCK_ARGUMENT_TYPE')
  }
  checkOpaqueArgumentValue(value, path)
}

function makeSchemaTable(graph: GameplayModuleGraph): ReadonlyMap<string, GameplayRecordSchema> {
  const schemas = Array.isArray(graph.schemas) ? graph.schemas : []
  const table = new Map<string, GameplayRecordSchema>()
  for (const schema of schemas) {
    table.set(schema.id, schema)
    table.set(moduleSchemaKey(schema.id, schema.version), schema)
  }
  return table
}

function bindPreparedArguments(prepared: PreparedAuthorCodeBlock, values: unknown): AuthorCodeBlockArgumentBinding {
  const record = asRecord(values, 'arguments')
  for (const key of Reflect.ownKeys(record)) {
    if (typeof key !== 'string') fail('argument records cannot contain symbol keys', 'arguments', 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
    if (key === '__proto__' || key === 'prototype' || key === 'constructor') fail(`unsafe argument name "${key}"`, `arguments.${key}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
    const descriptor = Object.getOwnPropertyDescriptor(record, key)
    if (!descriptor || !('value' in descriptor) || !descriptor.enumerable) fail('argument records cannot contain accessors or non-enumerable values', `arguments.${key}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_VALUE')
  }
  const fields = prepared.argumentFields
  const names = new Set(fields.map(field => field.name))
  for (const key of Object.keys(record)) if (!names.has(key)) fail(`unknown argument "${key}"`, `arguments.${key}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_NAME')
  const schemas = makeSchemaTable(prepared.definition.graph)
  const payload: DataRecord = Object.create(null) as DataRecord
  for (const field of fields) {
    if (!own(record, field.name)) {
      if (field.optional) continue
      fail(`missing argument "${field.name}"`, `arguments.${field.name}`, 'AUTHOR_CODE_BLOCK_ARGUMENT_MISSING')
    }
    validateArgumentValue(record[field.name], effectiveArgumentType(field), schemas, `arguments.${field.name}`)
    payload[field.name] = record[field.name]
  }
  return { payload }
}

/**
 * Build and validate a block definition. The returned value is a fresh clone;
 * mutating it cannot mutate the caller's source object.
 */
export function createAuthorCodeBlock(
  input: AuthorCodeBlockCreateInput,
  registry: GameplayModuleRegistry = GAMEPLAY_MODULE_REGISTRY,
  compilerOptions?: GameplayModuleCompilerOptions,
): AuthorCodeBlock {
  return validateAuthorCodeBlock({
    version: AUTHOR_CODE_BLOCK_VERSION,
    id: input.id,
    graph: input.graph,
    ...(input.signature === undefined ? {} : { signature: input.signature }),
  }, registry, compilerOptions)
}

/** Validate and return a fresh, compiler-checked data-only block clone. */
export function validateAuthorCodeBlock(
  value: unknown,
  registry: GameplayModuleRegistry = GAMEPLAY_MODULE_REGISTRY,
  compilerOptions?: GameplayModuleCompilerOptions,
): AuthorCodeBlock {
  return prepareAuthorCodeBlock(value, registry, compilerOptions).definition
}

/** Compile a validated block. The compiler output is trusted generated code. */
export function compileAuthorCodeBlock(
  value: unknown,
  registry: GameplayModuleRegistry = GAMEPLAY_MODULE_REGISTRY,
  compilerOptions?: GameplayModuleCompilerOptions,
): AuthorCodeBlockCompilation {
  const prepared = prepareAuthorCodeBlock(value, registry, compilerOptions)
  return { definition: prepared.definition, signature: prepared.signature, compiled: prepared.compiled }
}

/**
 * Compile a block and bind explicit runtime arguments through `ctx.payload`.
 * Runtime values are never written into or cloned into the persisted block.
 */
export function compileAuthorCodeBlockWithArguments(
  value: unknown,
  argumentsValue: unknown,
  registry: GameplayModuleRegistry = GAMEPLAY_MODULE_REGISTRY,
  compilerOptions?: GameplayModuleCompilerOptions,
): AuthorCodeBlockInvocation {
  const prepared = prepareAuthorCodeBlock(value, registry, compilerOptions)
  const argumentBinding = bindPreparedArguments(prepared, argumentsValue)
  return { definition: prepared.definition, signature: prepared.signature, compiled: prepared.compiled, argumentBinding }
}

/** Revalidate and bind arguments without exposing a callback or interpreter. */
export function bindAuthorCodeBlockArguments(
  value: unknown,
  argumentsValue: unknown,
  registry: GameplayModuleRegistry = GAMEPLAY_MODULE_REGISTRY,
  compilerOptions?: GameplayModuleCompilerOptions,
): AuthorCodeBlockArgumentBinding {
  const prepared = prepareAuthorCodeBlock(value, registry, compilerOptions)
  return bindPreparedArguments(prepared, argumentsValue)
}

/** Explicit alias for callers that name the operation after its binding step. */
export const compileAuthorCodeBlockWithArgumentBinding = compileAuthorCodeBlockWithArguments

